export function demoResult(profile: Profile, track: number): Result {
  const data = tracks[track];
  return {
    strategy: "demo-curated",
    mode: profile.stage ? "personalized" : "cold_start",
    clarification: profile.stage
      ? null
      : "Подборка доступна и без профиля. Уточните стадию бизнеса, чтобы сделать её полезнее.",
    recommendations: data.titles.map((title, i) => ({
      material: {
        id: `demo-${track}-${i}`,
        title,
        summary: data.summaries[i],
        format: i === 1 ? "template" : i === 3 ? "course" : "article",
        topics: [data.topic],
        industries: [],
        stages: [],
        level: "beginner",
        access: i === 3 ? "paid" : "free",
        url: null,
        related: [],
        popularity: 0,
      },
      reasons: [
        `В этом тестовом сценарии материал помогает разобрать задачу «${data.topic.toLowerCase()}» и перейти к практическому действию.`,
      ],
      next_step: [
        "Определите, что мешает сейчас.",
        "Подготовьте рабочий план.",
        "Проверьте один инструмент на практике.",
        "Выберите следующий шаг развития.",
      ][i],
    })),
  };
}
